'use client';

import React, { useState, useEffect } from 'react';
import { useApp } from '@/components/AppContext';
import { NotificationOutboxItem } from '@/types';
import { BrevoReminderTrigger } from '@/components/BrevoReminderTrigger';
import { 
  Mail, 
  Send, 
  CheckCircle2, 
  Clock, 
  AlertCircle, 
  ShieldCheck, 
  Eye, 
  X,
  RefreshCw
} from 'lucide-react';

export default function NotificationsPage() {
  const { currentProfile, refreshKey, triggerRefresh, showNotification } = useApp();
  const [outbox, setOutbox] = useState<NotificationOutboxItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [processing, setProcessing] = useState(false);
  const [selectedItem, setSelectedItem] = useState<NotificationOutboxItem | null>(null);

  useEffect(() => {
    setLoading(true);
    fetch(`/api/notifications?profileId=${currentProfile.id}`)
      .then((res) => res.json())
      .then((data) => {
        if (data.outbox) {
          setOutbox(data.outbox);
        }
      })
      .catch((err) => console.error(err))
      .finally(() => setLoading(false));
  }, [currentProfile.id, refreshKey]);

  const handleProcessOutbox = async () => {
    setProcessing(true);
    try {
      const res = await fetch('/api/notifications', { method: 'POST' });
      const data = await res.json();
      if (!res.ok) {
        showNotification('Error processing notifications');
      } else {
        showNotification(`Worker completed: Processed ${data.processed} item(s) (${data.succeeded} dispatched, ${data.failed} failed)`);
        triggerRefresh();
      }
    } catch (err: any) {
      showNotification(`Error: ${err.message}`);
    } finally {
      setProcessing(false);
    }
  };

  return (
    <div className="space-y-8">
      {/* Page Header */}
      <div className="bg-white rounded-2xl p-6 sm:p-8 border border-slate-200 shadow-sm flex flex-col md:flex-row md:items-center md:justify-between gap-6">
        <div>
          <div className="inline-flex items-center gap-2 bg-kalji-50 text-kalji-800 text-xs font-bold px-3 py-1 rounded-full mb-2">
            <Mail className="w-3.5 h-3.5" aria-hidden="true" />
            <span>Development Email Sink</span>
          </div>
          <h1 className="text-3xl font-extrabold text-slate-900 tracking-tight">
            Notification Outbox &amp; Email Dispatcher
          </h1>
          <p className="text-slate-600 mt-1 font-medium">
            Proactive email reminders for upcoming doses, unconfirmed grace alerts, and appointments.
          </p>
        </div>

        <button
          onClick={handleProcessOutbox}
          disabled={processing}
          className="min-h-touch px-6 py-3 bg-kalji-700 hover:bg-kalji-800 text-white font-extrabold text-sm rounded-xl shadow transition-colors flex items-center justify-center gap-2 self-start md:self-auto disabled:opacity-50"
        >
          <RefreshCw className={`w-4 h-4 ${processing ? 'animate-spin' : ''}`} aria-hidden="true" />
          <span>{processing ? 'Processing...' : 'Process Outbox Worker'}</span>
        </button>
      </div>

      {/* Privacy Notice */}
      <div className="bg-cream-100 border border-slate-200 rounded-xl p-4 flex items-start gap-3">
        <ShieldCheck className="w-5 h-5 text-kalji-700 flex-shrink-0 mt-0.5" aria-hidden="true" />
        <div className="text-xs sm:text-sm text-slate-700 leading-relaxed">
          <strong>Privacy Preserving Template Standard (FR-027):</strong> Every email generated by KaljiHome is strictly scrubbed of medication names, strengths, and medical diagnoses to safeguard user confidentiality on lock screens and shared inboxes. Recipients receive neutral reminders that link directly to their authenticated dashboard.
        </div>
      </div>

      {/* Live Brevo Gmail Dispatcher */}
      <BrevoReminderTrigger
        defaultEmail="patilsakshi18027@gmail.com"
        elderName={currentProfile.preferred_name}
        onSent={() => triggerRefresh()}
      />

      {/* Outbox List */}
      {loading ? (
        <div className="p-12 text-center text-slate-500 bg-white rounded-2xl border border-slate-200">
          Loading notification outbox...
        </div>
      ) : outbox.length === 0 ? (
        <div className="p-12 text-center text-slate-500 bg-white rounded-2xl border border-slate-200">
          No notifications currently queued in the outbox.
        </div>
      ) : (
        <div className="space-y-4">
          <div className="flex items-center justify-between">
            <h2 className="text-xl font-extrabold text-slate-900">
              Notification Records ({outbox.length})
            </h2>
            <span className="text-xs text-slate-500 font-medium">
              Mode: Development Sink (Transparent Delivery Log)
            </span>
          </div>

          <div className="grid grid-cols-1 gap-4">
            {outbox.map((item) => {
              const isDispatched = item.status === 'dispatched';
              const isQueued = item.status === 'queued';
              const isFailed = item.status === 'failed';

              return (
                <div
                  key={item.id}
                  className="bg-white rounded-2xl p-5 sm:p-6 border border-slate-200 shadow-sm flex flex-col md:flex-row md:items-center justify-between gap-6"
                >
                  <div className="space-y-2">
                    <div className="flex flex-wrap items-center gap-2.5">
                      <span className={`text-xs font-extrabold uppercase tracking-wider px-2.5 py-0.5 rounded-full flex items-center gap-1 ${
                        isDispatched ? 'bg-emerald-100 text-emerald-800' :
                        isQueued ? 'bg-blue-100 text-blue-800' :
                        'bg-red-100 text-red-800'
                      }`}>
                        {isDispatched ? <CheckCircle2 className="w-3.5 h-3.5" /> :
                         isQueued ? <Clock className="w-3.5 h-3.5" /> :
                         <AlertCircle className="w-3.5 h-3.5" />}
                        <span>{item.status}</span>
                      </span>

                      <span className="text-xs font-bold bg-slate-100 text-slate-700 px-2 py-0.5 rounded">
                        Type: {item.notification_type.replace('_', ' ')}
                      </span>
                    </div>

                    <h3 className="text-lg font-extrabold text-slate-900">
                      Subject: &quot;{item.email_subject}&quot;
                    </h3>

                    <p className="text-xs text-slate-600 font-medium">
                      Recipient: <strong className="text-slate-800">{item.recipient_email}</strong> ({item.recipient_name})
                    </p>

                    <div className="flex flex-wrap items-center gap-3 text-[11px] text-slate-500 pt-1">
                      <span>Scheduled for: {new Date(item.scheduled_for_utc).toLocaleString()}</span>
                      {item.dispatched_at_utc && (
                        <span>• Dispatched at: {new Date(item.dispatched_at_utc).toLocaleString()}</span>
                      )}
                      <span>• Attempts: {item.attempt_count} of {item.max_attempts}</span>
                    </div>
                  </div>

                  <button
                    onClick={() => setSelectedItem(item)}
                    className="min-h-touch px-4 py-2 border border-slate-300 text-slate-700 font-bold text-xs rounded-xl hover:bg-slate-50 flex items-center justify-center gap-1.5 transition-colors self-start md:self-auto"
                  >
                    <Eye className="w-4 h-4 text-slate-500" aria-hidden="true" />
                    <span>Preview Message</span>
                  </button>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* Message Preview Modal */}
      {selectedItem && (
        <div className="fixed inset-0 bg-slate-900/60 backdrop-blur-sm z-50 flex items-center justify-center p-4 overflow-y-auto" role="dialog" aria-modal="true" aria-labelledby="preview-title">
          <div className="bg-white rounded-2xl max-w-xl w-full p-6 sm:p-8 shadow-2xl border border-slate-200 space-y-6 my-8">
            <div className="flex items-center justify-between border-b border-slate-200 pb-4">
              <div className="flex items-center gap-2">
                <Mail className="w-6 h-6 text-kalji-700" aria-hidden="true" />
                <h2 id="preview-title" className="text-xl font-extrabold text-slate-900">
                  Email Message Preview
                </h2>
              </div>
              <button
                onClick={() => setSelectedItem(null)}
                className="p-2 text-slate-400 hover:text-slate-600 rounded-lg"
                aria-label="Close dialog"
              >
                <X className="w-6 h-6" />
              </button>
            </div>

            <div className="bg-slate-50 p-4 rounded-xl border border-slate-200 text-xs space-y-2">
              <p><strong>To:</strong> {selectedItem.recipient_email} ({selectedItem.recipient_name})</p>
              <p><strong>Subject:</strong> {selectedItem.email_subject}</p>
              <p><strong>Delivery Status:</strong> <span className="uppercase font-bold">{selectedItem.status}</span></p>
            </div>

            <div className="border border-slate-200 rounded-xl p-5 bg-white text-xs sm:text-sm text-slate-700 font-mono whitespace-pre-wrap leading-relaxed">
              {selectedItem.email_body}
            </div>

            <div className="flex justify-end pt-2">
              <button
                onClick={() => setSelectedItem(null)}
                className="min-h-touch px-6 py-2.5 bg-slate-900 hover:bg-slate-800 text-white font-bold rounded-xl"
              >
                Close Preview
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
